    <h2 class="section-title">Функции и роль в священной<br>истории</h2>

    <div class="info-block">
        <p><strong>Служение Богу:</strong> Ангелы предстоят пред Престолом Всевышнего, непрестанно славя и воспевая Его святость. Их служение заключается в созерцании Божественной славы и участии в небесной литургии. Пророк Исаия созерцал серафимов, взывающих друг к другу: "Свят, Свят, Свят Господь Саваоф!", что открывает вечную реальность ангельского поклонения.</p>

        <p><strong>Откровение:</strong> Как вестники Божественной воли, ангелы являются посредниками в передаче людям спасительных истин. Архангел Гавриил благовестил Деве Марии о Воплощении Сына Божия, возвещал рождение Предтечи Захарии, объяснял пророку Даниилу мессианские пророчества. Через ангелов Бог открывает Свой замысел о спасении человечества, направляя ход священной истории.</p>

        <p><strong>Защитники и Хранители:</strong> Учение о личном Ангеле-Хранителе утверждено словами Самого Спасителя: "Смотрите, не презирайте ни одного из малых сих; ибо говорю вам, что Ангелы их на небесах всегда видят лице Отца Моего Небесного". Каждому верующему от Крещения до смерти сопутствует ангел, охраняющий его душу от искушений и наставляющий на путь спасения.</p>

        <p><strong>Исполнители Божьего суда:</strong> В эсхатологическом свершении Божественного правосудия ангелы активно участвуют как исполнители воли Вседержителя. В книге Откровения они изливают чаши гнева на грешный мир, сопровождают Христа в Его славном пришествии и отделяют избранных от осужденных. Их служение проявляет одновременно Божию справедливость и милосердие.</p>

        <p><strong>Помощь в деле спасения:</strong> На протяжении всего земного служения Господа Иисуса Христа ангелы оказывали Ему благоговейное послушание. Они служили Ему после победы над искушениями в пустыне, укрепляли в молитвенном борении в Гефсиманском саду, отвалили камень от дверей гроба и возвестили мироносицам о Воскресении, став первыми провозвестниками пасхальной радости.</p>

        <p><strong>Сопровождение душ:</strong> Согласно церковному преданию, основанному на словах Спасителя, восхищенном ангелами на лоно Авраамово, бесплотные силы сопровождают души праведников в райские обители после их телесной кончины. Это служение проявляет попечение Божие о человеке не только во временной жизни, но и за её пределами.</p>
    </div>

