    <h2 class="section-title">Падение ангелов</h2>

    <div class="content-block">
        <div class="content-image">
            <img src="/images/angelhris4.png" alt="Падение ангелов">
        </div>
        <div class="content-text">
            <p>Христианство учит, что не все ангелы остались верны Богу. Согласно учению, часть из них, во главе с самым могущественным, мудрым и прекрасным ангелом — Денницей (что означает «Сын зари»), более известным как Люцифер («Несущий свет»), совершила трагический выбор. Причина их падения коренится не в физическом бунте, а в духовной катастрофе — гордыне.</p>

            <p>В результате они были низвергнуты с неба и стали демонами (бесами). Это событие описывается в аллегорической форме в Откровении и подтверждается словами Христа: «Я видел сатану, спадшего с неба, как молнию». Грех падших ангелов — гордыня и противление воле Божьей.</p>
        </div>
