    <h2 class="section-title">Начала</h2>

    <div class="content-block">
        <div class="content-text">
            <p>Начала (archai) занимают высшую ступень в низшей ангельской триаде, выполняя уникальную роль посредников между божественным замыслом и человеческим сообществом. Их служение связано с управлением целыми народами, государствами и историческими эпохами, что делает их не просто исполнителями, но стратегами космического порядка.</p>

            <p>В отличие от высших чинов, Начала действуют не через созерцание, а через активное влияние — они внушают правителям мудрые мысли, направляют их к справедливости и помогают осознать ответственность перед Богом и народом.</p>

            <p>Особенность служения Начал заключается в масштабности их попечения. Согласно христианскому преданию, у каждого народа есть свой Ангел-Покровитель, подчиняющийся воле Бога.</p>
        </div>
        <div class="content-image">
            <img src="/images/nachaloosn.png" alt="Начала">
        </div>
    </div>

    <div class="info-block">
