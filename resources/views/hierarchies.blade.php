        <h2 class="section-title">Престолы</h2>

        <div class="content-block">
            <div class="content-image">
                <img src="/images/prestolosn.png" alt="Престолы">
            </div>
            <div class="content-text">
                <p>В видениях пророков Престолы предстают как огненные колёса, покрытые множеством очей. Этот образ, описанный у Иезекииля, глубоко символичен: колёса означают неустанное движение Божьего замысла в мире, а очи — всевидящую проницательность Божественного правосудия, которое проникает в самую суть вещей. Престолы обладают способностью нести в себе обители Божьей природы — тронами, являющимися в будущем — в свете вечной Божьей природы.</p>

                <p>В духовной жизни верующих Престолы помогают обрести «духовную неподвижность» — устойчивость в вере перед любыми испытаниями и искушениями. Когда христианин сохраняет мир в сердце среди жизненных бурь, или проявляет непоколебимость в исповедании истины — это действие данного ангельского чина.</p>
            </div>
        </div>

        <div class="info-block">
            <p>Особенностью Престолов является их полная неподвижность в Боге. В то время как другие ангелы перемещаются для исполнения поручений, Престолы пребывают в постоянном созерцании Божественной Правды. Это неподвижность — не пассивность, а высшая форма активности, состоящая в совершенном принятии и отражении Божьей воли. Через их служение Бог являет Себя как Творца и основание всего существующего.</p>

            <p>Через служение Престолов Бог являет миру Свою верность и неизменность. Их присутствие в духовном мире напоминает, что вселенная основана на законах правды и справедливости, и что одно действие — добро или зло — не остаётся без последствий. Они свидетельствуют, что конечная цель творения — установление Царства Божия, где правда и мир обнимутся в совершенной гармонии.</p>
        </div>

        <div class="intro-section-text">
            <p>Такие образы, низшая иерархия представляет собой совершенную систему Божьего попечения о мире: от управления целыми народами (Начала) через возвещение ключевых истин (Архангелы) к индивидуальному заботе о каждой человеческой душе (Ангелы). Эта триада демонстрирует, что Божественная любовь и промысел распространяются на все, на мельчайшие детали человеческой жизни.</p>
