            <p>Через служение Властей Бог являет Своё попечение о судьбах человеческой воли. Они не уничтожают зло полностью, но ограничивают его влияние, давая человеку возможность свободного выбора между добром и злом.</p>

            <p>Их постоянное моральное присутствие напоминает, что ни одно духовное не превосходит того человека, а в любой духовной борьбе верующий могут рассчитывать на небесную поддержку.</p>

            <p>Основным служением ангелов является хранение и спасение каждой человеческой души. Согласно церковному учению, у каждого крещёного есть свой Ангел-Хранитель, который дарует ему в Таинстве Крещения. Этот незримый спутник остаётся с человеком на протяжении всей жизни — утешает в скорбях, предостерегает от греха, утешает в молитве и духовном росте. После смерти душа усопшего поручается своему ангелу-хранителю для сопровождения в загробный мир.</p>

            <p>Ангелы выполняют бесчисленное множество поручений, служа проводниками Божьих Промысла. Они приносят Богу молитвы верующих, вдохновляют на благие помыслы, защищают от опасностей — как физических, так и духовных. В житиях святых описаны случаи, когда ангелы принимали человеческий облик, чтобы накормить голодного, вывести путника из непроходимой местности или избавить узника. При этом они всегда действуют тактично, уважая человеческую свободу воли.</p>
