        <h2 class="section-title">Серафимы</h2>

        <div class="content-block">
            <div class="content-image">
                <img src="/images/serafimosn.png" alt="Серафимы">
            </div>
            <div class="content-text">
                <p>Серафимы занимают высшее положение в ангельской иерархии, находясь в непосредственной близости к Божественному Престолу. Их название происходит от древнееврейского слова, означающего «пылающий» или «горящий», что отражает их основную характеристику — пламенную любовь к Богу и способность очищать всё окружающее божественным огнём. Серафимы представляют собой совершенный образ устремлённости тварного существа к своему Творцу.</p>

                <p>Согласно видению пророка Исаии, серафимы имеют шесть крыльев, каждое из которых символизирует определённый аспект их служения. Двумя крыльями они закрывают своё лицо, не смея взирать на Божественную славу; двумя крыльями покрывают ноги, выражая благоговение и смирение; двумя крыльями летают, исполняя Божьи повеления.</p>

                <p>Особой функцией серафимов является очищение и духовное преображение других ангелов и человеческих душ. В том же видении Исаии один из серафимов коснулся уст пророка горящим углём, взятым с жертвенника, говоря: «Вот, это коснулось уст твоих, и беззаконие твоё удалено от тебя, и грех твой очищен». Это действие символизирует очищающую силу Божественной любви, неотъемлемую часть вечного служения серафимов.</p>

                <p>В иконографии серафимы изображаются как шестикрылые существа, обычно красного цвета, символизирующего их пламенную природу. Иногда их рисуют в человеческом облике, но чаще — в виде огненных колёс или крыльев, что указывает на их отдалённость от материального мира и полное погружение в созерцание Бога. Их образы часто изображаются в окружении божественного света, подчёркивая их роль как проводников божественной энергии.</p>

                <p>Через служение серафимов Бог являет миру образ совершенной любви — любви, которая одновременно и сжигает всё нечистое, и воспламеняет сердца к духовным подвигам. Их пример вдохновляет верующих на молитвенное горение и устремлённость к Богу, напоминая, что конечная цель человеческой жизни — соединение с Творцом в любви и вечной славе.</p>
            </div>
        </div>

        <div class="info-block">
            <p>Серафимы — высший чин ангельской иерархии. Их имя означает "пламенные" или "пылающие". Они предстоят ближе всего к Престолу Божьему и непрерывно славят Бога, взывая: "Свят, Свят, Свят Господь Саваоф!" (Исаия 6:2-3). Серафимы изображаются шестикрылыми: двумя крыльями они закрывают лицо, двумя — ноги, и двумя — летают.</p>
