        <p>Такие образы, средняя иерархия представляет собой могущественный «административный слой» ангелов небесного воинства. Господства могут как разумное управление, Силы проявляют божественную премудрость в чудесах, Власти — как хранители порядка и разрушительные деяния зла. Вместе они образуют совершенную систему, через которую Божественная воля претворяется в законы природы и истории, сохраняя вселенскую гармонию между горним и дольним мирами.</p>
