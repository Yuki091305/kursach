    <!-- АРХАНГЕЛЫ -->
    <h2 class="section-title">Архангелы</h2>

    <div class="content-block reverse">
        <div class="content-text">
            <p>Архангелы занимают центральное место в низшей ангельской триаде, выступая как верховные вестники Божьей воли и предводители небесных воинств. Их имя с греческого переводится как «старшие ангелы», что отражает их роль вождей и наставников для остальных ангельских чинов. В отличие от других чинов, Архангелы чаще всего называются по именам, что делает их наиболее узнаваемыми и почитаемыми в христианской традиции.</p>

            <p>Главной функцией Архангелов является возвещение важных тайн Божьих и управление верой в человеческих сердцах. Именно Архангел Гавриил принёс Деве Марии весть о Воплощении Сына Божия, открыв новую эру в истории спасения. Архангел Рафаил в Книге Товита выступает как целитель и путеводитель, демонстрируя попечение Божие о повседневных нуждах людей. Архангел Михаил, чьё имя означает «Кто как Бог?», возглавляет борьбу с тёмными силами, являя духовную чистоту и силу верных Богу.</p>

            <p>Особое значение имеет воинское служение Архангелов. Они организуют и возглавляют ангельские воинства в битве с силами тьмы, защищая как отдельные души, так и всё творение от разрушительного влияния зла. В Откровении Иоанна Богослова описывается, как Михаил и его ангелы сражаются с драконом, что подчёркивает их роль как защитников Божественного порядка. При этом их оружие является не физическим, но духовным — мечом и верностью Богу.</p>

            <p>В церковном предании почитается семь Архангелов, хотя в канонических книгах Писания упоминаются только трое: Михаил, Гавриил и Рафаил. К ним добавляются Уриил (Огонь или Свет Божий), Селафиил (Молитвенник Божий), Иегудиил (Хвала Божья) и Варахиил (Благословение Божье). Каждый из них представляет определённый аспект Божественного действия в мире.</p>

            <p>Иконографически Архангелов изображают как прекрасных юношей в воинских доспехах либо в царских одеждах, с мечами, жезлами или держащими в руках различные символы. Часть в руках Архангела Михаила изображает меч или копьё, которым он поражает дракона.</p>
        </div>
        <div class="content-image">
            <img src="/images/arhangelosn.png" alt="Архангелы">
        </div>
    </div>

    <div class="info-block">
        <p>Через служение Архангелов Бог особенно явно проявляет Своё попечение о мире. Они связывают в себе силу и милосердие, власть и одновременно трепетную нежность к небесным созданиям человечества. Их постоянное присутствие перед Богом делает их могущественными ходатаями за людей перед престолом Всевышнего.</p>
    </div>

