            <p>Именно эта монотеистическая, строго выверенная и подчинённая концепция служебных духов и стала тем прочным фундаментом, на котором впоследствии возникли свои детализированные и масштабные учения об ангелах две другие авраамические религии — христианство и ислам. Иудаизм предоставил им не просто набор образов, а целостную систему, в рамках которой можно было дальше развивать и усложнять представления о небесном воинстве.</p>
